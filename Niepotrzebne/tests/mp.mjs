// Battle with Ideas: two real browser sessions on the test realm (real Firebase + WebRTC), with assertions.
import { createRequire } from 'node:module';
const require = createRequire('/Users/jurek/openclaw/node_modules/');
const { chromium } = require('playwright-core');
const URL = (process.env.URL || 'http://127.0.0.1:8963/') + '?test=1&realm=test';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const mk = async (name) => {
  const ctx = await browser.newContext({ viewport: { width: 960, height: 540 } });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => console.log(`[${name} pageerror] ${e.message}`));
  page.on('console', (m) => { if (m.type() === 'error' && !/404|ERR_CONN|pointer lock/.test(m.text())) console.log(`[${name}] ${m.text()}`); });
  await page.goto(URL);
  await page.waitForFunction(() => window.BWI && document.getElementById('boot').classList.contains('off'), null, { timeout: 60000 });
  await page.evaluate((n) => { BWI.app.profile.name = n; BWI.app.saveProfile(); BWI.game.me.name = n; }, name);
  return page;
};
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
const mode = process.argv[2] || 'ffa';
const A = await mk('Ala'), B = await mk('Bob');
await A.evaluate(async () => { const r = await BWI.app.api.resolve('skafander', 'outfit', 'Ala'); BWI.game.wearOutfit(r.rec.outfit, r.rec.name, false); });
const code = await A.evaluate(async (mode) => { await BWI.app.createRoom(mode, true); return BWI.app.session.code; }, mode);
ok(/^[A-Z]{4}$/.test(code), 'room created ' + code);
await B.evaluate(async (c) => { await BWI.app.joinRoom(c); }, code);
await A.waitForTimeout(3500);
const rosterA = await A.evaluate(() => BWI.app.session.roster().map((p) => p.n));
ok(rosterA.length === 2, 'host sees 2 players: ' + rosterA.join(','));
await A.evaluate(() => BWI.app.session.start());
await A.waitForTimeout(6000);
const stA = await A.evaluate(() => ({ mode: BWI.game.mode.kind, st: BWI.game.mode.st, peers: BWI.app.session.stats(), players: [...BWI.game.players.values()].map((p) => p.name + (p.remote ? ':' + p.hasPose : '')) }));
const stB = await B.evaluate(() => ({ mode: BWI.game.mode.kind, st: BWI.game.mode.st, peers: BWI.app.session.stats(), players: [...BWI.game.players.values()].map((p) => p.name + (p.remote ? ':' + p.hasPose : '')) }));
console.log('A', JSON.stringify(stA)); console.log('B', JSON.stringify(stB));
ok(stA.mode === stB.mode && stA.mode === (mode === 'coop' ? 'coop' : mode), 'both in mode ' + stA.mode);
ok(stB.players.some((p) => p.endsWith(':true')), 'B sees A pose');
await A.evaluate(async () => { BWI.game.cam.pitch = -0.3; await BWI.game.cast('rekin z laserami'); });
await A.waitForTimeout(2500);
const seenB = await B.evaluate(() => [...BWI.game.ideas.map.values()].map((i) => `${i.rec.name}:${i.owner.slice(0, 4)}:${i.isOwner}`));
ok(seenB.some((s) => s.startsWith('Rekin')), 'B sees A idea: ' + seenB.join(' | '));
await B.evaluate(async () => { BWI.game.me.wena = 100; await BWI.game.cast('chcę być rycerzem'); });
await A.waitForTimeout(2500);
const fits = (P) => P.evaluate(() => [...BWI.game.players.values()].filter((p) => p.remote).map((p) => `${p.name}:${p.puppet.pieces.length}:${!!(p.outfit && p.outfit.head)}`));
const fitB = await fits(B), fitA = await fits(A);
ok(fitB.some((s) => /^Ala:[1-9]\d*:true$/.test(s)), 'B sees the spacesuit A put on before joining: ' + fitB.join(','));
ok(fitA.some((s) => /^Bob:[1-9]\d*:/.test(s)), 'A sees the armour B cast in the match: ' + fitA.join(','));
await B.screenshot({ path: 'Niepotrzebne/tests/out/mp-b.png' });
await A.screenshot({ path: 'Niepotrzebne/tests/out/mp-a.png' });
await A.evaluate(() => BWI.app.toMenu()); await B.evaluate(() => BWI.app.toMenu());
await A.waitForTimeout(1500);
await browser.close();
